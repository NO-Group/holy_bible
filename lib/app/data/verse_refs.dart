/// Deterministic day index for the verse of the day (resets each day,
/// cycles through the curated list).
int verseOfTheDayIndex(DateTime now) =>
    now.toUtc().difference(DateTime.utc(2024, 1, 1)).inDays %
    kVerseOfTheDay.length;
